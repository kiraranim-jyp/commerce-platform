-- ════════════════════════════════════════════════════════════════════════════
-- COMMON-AS-PHONE-SEPARATION-01 — A/S 「전화번호」를 «안내문» 과 가른다
-- (CPO 결정 B, 2026-09-29)
-- ════════════════════════════════════════════════════════════════════════════
--
-- ── 왜 새 칸인가 ───────────────────────────────────────────────────────────
-- `as_contact_number` 는 이름이 「연락처」지만 실제로는 **A/S 안내문** 이다.
-- 그 사실은 추측이 아니라 실측이다(N-3.51 · 5차 실등록):
--
--     네이버 afterServiceDirector        자유 텍스트 고시 항목
--                                        「해외 구매대행으로 A/S 불가」가 통과한다
--     네이버 afterServiceTelephoneNumber 숫자/-/+ 만 허용하는 «엄격한» 전화번호
--     → 같은 소스를 재사용할 수 없다
--
-- 그래서 그 칸을 번호로 «되돌리지» 않는다 — 되돌리면 네이버 고시 문구가 번호로
-- 바뀌어 회귀한다(CPO 결정: 선택지 A 탈락).
--
-- 롯데ON 고시 `0090` 은 「AS책임자(업체명)와 전화번호를 모두」를 요구한다.
-- 업체명은 068 이 만들었고, 이 파일이 **번호 자리**를 만든다.
--
-- ── 🔴 backfill 하지 않는다 ────────────────────────────────────────────────
-- 옮겨올 것이 없다. `as_contact_number` 에는 문장이 들어 있고, 문장에서 번호를
-- 뽑아내지 않는다(CPO 금지). `company_contact_number`(배송 프로필의 «반품지»
-- 연락처)를 자동으로 끌어오지도 않는다 — 다른 개념이다.
-- 셀러가 직접 입력하기 전까지 이 칸은 NULL 이고, 그 사실이 화면에 그대로 뜬다.
--
-- ── 🔴 컬럼이 생기기 «전» 에 코드가 배포돼도 안전하다 ──────────────────────
-- 068 과 같은 장치가 이미 있다 — 읽기 경로가 `42703`(undefined_column) «하나만»
-- 골라 구 컬럼 목록으로 한 번 더 읽는다. 다른 오류는 그대로 ERROR 다.
-- 그 계약은 `seller-settings-column-fallback.test.ts` 가 고정한다.
--
-- 실행: CEO 가 Supabase SQL Editor 에서 실행한다(에이전트는 실행하지 않는다).

ALTER TABLE seller_settings
  ADD COLUMN IF NOT EXISTS as_phone_number text;

COMMENT ON COLUMN seller_settings.as_phone_number IS
  'A/S 전화번호. 🔴 as_contact_number(= A/S 안내 문구)와 «다른 칸» 이다 — 후자는 네이버 고시에서 자유 텍스트로 실측 통과한 값이라 번호로 바꾸면 회귀한다. 반품지 연락처(company_contact_number)로 대신 채우지도 않는다.';
