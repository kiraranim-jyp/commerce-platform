-- 073 — 다나와를 «공통» 가격비교 소스로 올린다 (CEO 승인, 2026-10-04)
-- ════════════════════════════════════════════════════════════════════════════
--
-- 052 가 다나와를 `array['GOLF']` 로 넣었다. 그때는 골프 작업이었고 그것이 맞았다.
-- 그런데 다나와는 «국내 최대 가격비교 포털» 이고 골프 전용이 아니다 — 테니스·
-- 패션·라이프스타일 어느 카테고리에서도 같은 역할을 한다.
--
-- 🔴 072 는 이 UPDATE 를 «하지 않았다». 「기존 사이트의 데이터를 임의 UPDATE 하지
-- 않는다」(CEO 지시 8) 때문이다. 이 파일은 **CEO 가 명시적으로 승인한 뒤** 그
-- 한 행만 바꾼다(CTO-TENNIS-MARKET-SOURCE-03-FINAL ①).
--
-- ── 🔴 잃는 것이 없다 ─────────────────────────────────────────────────────
-- `sourceFitsScopes` 는 빈 배열을 「모든 카테고리」로 읽는다(profiles.ts:502-506).
-- 그래서 `array['GOLF']` → `'{}'` 는 **GOLF 에서 빼는 것이 아니라 전부에 더하는
-- 것** 이다. 골프 조사 대상은 한 곳도 줄지 않는다.
--
-- ── 바꾸는 칸과 바꾸지 «않는» 칸 ──────────────────────────────────────────
--   category_scope   array['GOLF'] → '{}'      ← 이 한 칸만 바꾼다
--   access_status    'OK' 그대로               ← 052 가 2026-09-15 실측으로 적었다
--   status           'ACTIVE' 그대로
--   collection_strategy 'MANUAL' 그대로        ← 🔴 파서는 여전히 없다
--   enabled          true 그대로
--   source_role       'PRICE_COMPARISON' 그대로 (053)
--
-- 🔴 `collection_strategy` 를 AUTO 로 올리지 «않는다». 다나와용 파서는 저장소에
-- 없다(price-source-adapter 목록에 없음). 「공통 소스다」와 「자동으로 읽는다」는
-- 다른 사실이고, 둘을 같이 올리면 그 순간 화면이 거짓말한다.
--
-- ── 🔴 범위를 한 행으로 좁힌다 ────────────────────────────────────────────
-- `where domain = 'danawa.com'` 이다. 도메인은 unique(029:15)이므로 최대 1행이
-- 바뀐다. 🔴 `where category_scope = array['GOLF']` 같은 조건으로 «여러 행» 을
-- 쓸어 담지 않는다 — 네이버 쇼핑도 같은 scope 를 갖고 있어서 그렇게 쓰면 둘이
-- 함께 바뀐다(아래 ③ 참고).
--
-- ── 이 파일이 하지 않는 것 ────────────────────────────────────────────────
-- ① 에누리를 건드리지 않는다.
--    화면 실측(2026-10-04, CEO): 에누리가 「수집 불가」로 보인다.
--    그 라벨은 `collection_strategy='NOT_AVAILABLE'` 이다(settings/page.tsx:3819).
--    🔴 그런데 072 는 에누리를 'MANUAL' 로 넣었다. 즉 **에누리 행은 072 «이전부터»
--    DB 에 있었고, `on conflict do nothing` 이 072 의 값을 버렸다.** 저장소에는
--    에누리 기록이 없었으므로(전수검색 0건) 운영 중에 다른 경로로 들어온 행이다.
--    CEO 지시 ②: "현재 수집 불가라면 임의로 OK/AUTO 로 바꾸지 않는다."
--    → 그래서 손대지 않는다. 그 행의 실제 값은 CTO 가 읽을 수 없다(§H).
-- ② 카카오 쇼핑하우를 건드리지 않는다 — 'MANUAL' 유지(CEO 지시 ③).
-- ③ 네이버 쇼핑을 건드리지 «않는다»(CEO 지시 ④).
--    053 이 'API_DISCONTINUED' + 'DEMAND_DATA' + status='NOT_AVAILABLE' 로 바꿨다.
--    공식 검색 API 가 2026-07-31 종료돼 «가격 수집 소스가 아니다». scope 를 고쳐도
--    `isCollectableAccess('API_DISCONTINUED') === false` 가 막으므로 돌아오지
--    않는다 — 고쳐 봐야 효과가 없고, 고치면 「복구했다」는 오해만 남는다.
-- ④ 해외 표(comparison_shops)를 건드리지 않는다.
-- ⑤ 새 사이트를 등록하지 않는다(insert 문이 없다). 행을 지우지 않는다.
-- ════════════════════════════════════════════════════════════════════════════

update domestic_price_sources
   set category_scope = '{}',
       access_note = access_note ||
         ' / 2026-10-04 073: 골프 전용(array[''GOLF''])에서 공통(모든 시장조사 카테고리)으로 올렸다. 국내 최대 가격비교 포털이라 카테고리를 가리지 않는다. collection_strategy=MANUAL 은 그대로 — 파서는 여전히 없다.',
       updated_at = now()
 where domain = 'danawa.com'
   and category_scope <> '{}';

