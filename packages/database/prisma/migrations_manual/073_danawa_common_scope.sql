-- 적용 후 기대 — 🔴 「표시」와 「조사 대상」은 다른 숫자다
-- ════════════════════════════════════════════════════════════════════════════
--
-- 설정 화면    「국내 N곳」 = catalogSourceCount
--                status='ACTIVE' && isCollectableAccess && sourceFitsScopes
--                && catalogEnabled(= 운영자 전역 스위치 domestic_price_sources.enabled)
--
-- 시장조사 화면 「조사 대상 N곳」 = sourceCount
--                위와 «같은» 네 조건 + workspaceEnabled(이 셀러가 자기 목록에서 켰는지)
--
-- 그래서 항상 `sourceCount <= catalogSourceCount` 다. 두 숫자가 다르면 그것은
-- 버그가 아니라 「운영자는 켰지만 이 셀러가 껐다」는 뜻이다.
--
-- 🔴 `collection_strategy` 는 **두 숫자 어디에도 들어가지 않는다.** 그래서
-- MANUAL 사이트도 두 숫자에 센다 — 「조사 대상 목록에 있다」는 뜻이고
-- 「자동으로 값을 가져온다」는 뜻이 아니다. 실제 수집은
-- comparison-search/index.ts:243 이 AUTO_API/AUTO_SCRAPE 만 통과시킨다.
--
-- 테니스 국내 예상(073 적용 후):
--     다나와            '{}' · ACTIVE · OK   · MANUAL  → 센다
--     카카오 쇼핑하우    '{}' · ACTIVE · null · MANUAL  → 센다
--     에누리            072 가 버려졌다 — 실제 값 미확인 → 셀지 알 수 없다
--     네이버 쇼핑        API_DISCONTINUED               → 세지 않는다
-- 🔴 그러므로 「2곳 또는 3곳」이고, 에누리 행의 실제 값을 본 뒤에 확정된다.
-- 숫자를 미리 단정하지 않는다.
