-- ════════════════════════════════════════════════════════════════════════════
--
-- ── 여기까지 온 길 ────────────────────────────────────────────────────────
-- 판매자 공통 다섯 값(제조사·A/S 연락처·품질보증기준·KC 문구·원산지 기본값)이
-- «배송 프로필» 표에 살고 있었다. 그 표는 여러 개를 갖는다(name + is_default).
-- 그래서 이런 일이 실제로 일어났다.
--
--     배송 프로필을 하나 더 만든다
--        → 판매자 정보가 «빈 채로» 새로 생긴다
--        → 그 프로필을 기본으로 바꾸면 판매자 정보가 «사라진다»
--
-- 가설이 아니었다. 실측 시점 DB 에 그 빈 행이 이미 둘 있었다.
--
--     059  seller_settings 신설 · 값이 있는 것만 backfill
--     060  전환 중 두 표를 함께 쓰는 임시 다리(dual-write)
--     A~C  읽기 → 화면 → 쓰기 순서로 canonical 로 옮김
--     D    입력 «계약» 에서 다섯 칸 제거 — 넣을 수 «없게» 만듦
--     E    READ/WRITE 전수 검증 — 레거시 write 경로 0건
--     F    060 함수 DROP
--     R6-FS 조회 «실패» 와 값 «없음» 을 가름(장애를 빈 값으로 위장하지 않음)
--     R6   임시 호환층 제거 — 레거시 read 경로 0건
--     G    이 파일 — 컬럼을 지운다
--
-- ── 🔴 실행 전 확인한 것(2026-09-23) ──────────────────────────────────────
--   레거시 5칸 READ 실행코드                    0
--   레거시 5칸 WRITE 실행코드                   0
--   coupang_seller_profiles 쿼리 6개 중
--     5칸을 «이름으로 지정» 하는 곳             0   (select("*") 뿐)
--   제약조건 · 인덱스 · 트리거 · 뷰/rule        0
--   생성컬럼 · 5칸 참조 public 함수             0
--   컬럼 5개 전부 존재 · text · nullable · default 없음
--
--   🔴 고유 정보 손실 0 — 레거시에 남아 있던 다섯 값이 seller_settings 의
--      값과 «전부 동일» 함을 대조로 확인했다. 지우는 것은 얼어붙은 사본이다.
--      (레거시는 F 이후 갱신되지 않았다 — 마지막 쓰기 2026-09-22 12:52:57)
--
--   실행 전 데이터는 저장소 «밖» 에 보존했다. 실제 값은 Git 에 남기지 않는다 —
--      제조사·연락처는 판매자의 사업자 정보다. 지문만 아래에 적는다.
--
--        legacy5 지문            c89c58a20bc241095a3ea326a3ef38b0
--        profile row count       3
--        나머지 컬럼 데이터 지문   168a3bc32166ea767d45d1706ca6610e
--        seller_settings 지문     afa6786803ea77dbebf8fabdb06cc9b8 (rows=1)
--
-- ── 🔴 이 migration 이 하는 일은 «컬럼 다섯 개 제거» 하나다 ────────────────
-- 행을 지우지 않는다(3행 그대로). 다른 컬럼을 건드리지 않는다(30개 그대로).
-- seller_settings 는 쳐다보지도 않는다. UPDATE 가 한 줄도 없다.
--
-- 되돌리려면 ALTER TABLE ... ADD COLUMN 으로 «빈» 컬럼을 되살릴 수는 있지만,
-- 값은 돌아오지 않는다. 다만 그 값들은 seller_settings 에 그대로 있다 —
-- 되살릴 이유가 생긴다면 그건 「판매자 정보를 다시 프로필마다 갖겠다」는
-- 뜻이고, 그건 PIVOT-03 전체를 되돌리는 결정이다.
--
-- 실행: CEO 승인하에 CTO 가 실행한다(G STEP 9).

ALTER TABLE public.coupang_seller_profiles
  DROP COLUMN manufacturer,
  DROP COLUMN as_contact_number,
  DROP COLUMN quality_guarantee,
  DROP COLUMN kc_exemption_text,
  DROP COLUMN default_country_of_origin;
