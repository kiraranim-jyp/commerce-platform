-- ════════════════════════════════════════════════════════════════════════════
-- LOTTEON-NOTICE-FIELD-IMPLEMENT-0090-01 — A/S «업체명» 을 담을 자리
-- (CPO 결정, 2026-09-29)
-- ════════════════════════════════════════════════════════════════════════════
--
-- ── 왜 필요한가 ────────────────────────────────────────────────────────────
-- 롯데ON 상품정보제공고시 품목 23(어린이제품)의 항목 `0090` 은
-- 「A/S 책임자와 전화번호」이고, 공식 작성 가이드라인이 이렇게 적는다:
--
--     「AS책임자(업체명)와 전화번호를 모두 입력해주세요.」
--
-- 우리에게는 `as_contact_number`(전화번호)만 있다. 그래서 그 항목은 채울 수
-- 없었고 등록이 BLOCKED 였다 — 값이 없어서가 아니라 «담을 칸이 없어서» 다.
--
-- ── 🔴 왜 기존 값으로 대신하지 않는가 (CPO 명시) ──────────────────────────
-- `manufacturer`(판매자 본인의 제조자/수입자)가 의미상 «가깝고» 실제로 같은
-- 문자열일 수도 있다. 그래도 쓰지 않는다 — 「제조자 자격」과 「A/S 를 책임지는
-- 업체」는 다른 사실이고, 고시는 후자를 묻는다. 판매자명·배송 프로필 이름도
-- 마찬가지다. 대신 넣으면 셀러가 확인한 적 없는 값이 고시로 나간다.
--
-- ── 🔴 backfill 하지 않는다 ────────────────────────────────────────────────
-- 옮겨올 원본이 없다. 저장소 전체에 「업체명/상호/사업자명」 의미의 칸이 하나도
-- 없다는 것을 전수 확인했다(LOTTEON-NOTICE-FIELD-CAPACITY-01/02).
-- 없는 것을 NULL 이 아닌 무언가로 만들면, 셀러는 자기가 입력한 적 없는 값이
-- 고시에 실린 것을 나중에 발견하게 된다.
--
-- ── 🔴 컬럼이 생기기 «전» 에 코드가 배포돼도 안전하다 ──────────────────────
-- 읽기 경로가 이 컬럼의 부재를 감지하면 구 컬럼 목록으로 한 번 더 읽는다
-- (apps/admin/src/lib/seller-settings.ts). 그래서 이 SQL 의 실행 시점과 배포
-- 순서가 서로를 깨뜨리지 않는다 — 쿠팡 실등록 경로가 그 사이에 막히면 안 된다.
--
-- 실행: CEO 가 Supabase SQL Editor 에서 실행한다(에이전트는 실행하지 않는다).

ALTER TABLE seller_settings
  ADD COLUMN IF NOT EXISTS as_company_name text;

COMMENT ON COLUMN seller_settings.as_company_name IS
  'A/S 를 «책임지는 업체» 의 이름. 🔴 제조사(manufacturer)도 배송 프로필 이름도 아니다. 롯데ON 고시 품목 23 항목 0090 이 「업체명과 전화번호를 모두」 요구해서 생겼다 — as_contact_number 와 한 쌍이다.';
