/**
 * ════════════════════════════════════════════════════════════════════════════
 * P5.6 P2(CPO ③, 2026-10-09) — **고시 품목코드를 «제안» 한다. 확정하지 않는다.**
 * ════════════════════════════════════════════════════════════════════════════
 *
 * CPO: 「`pd_itms_list` 빈 응답 원인 처리 · 의류 카테고리 선택 시 고시정보 자동 구성」.
 *
 * ── 🔴 원인은 이미 실측으로 닫혀 있다 ─────────────────────────────────────
 * 205 표준카테고리 응답의 `pd_itms_list` 는 **키는 있는데 배열이 항상 비어 있다** —
 * 목록 조회 6131건 중 nonEmpty 0건, `filter_1=std_cat_id` 단건 조회도 같다
 * (`category-recommend/route.ts` 의 1~3차 계측 기록). 즉 **채널이 그 값을 주지
 * 않는다.** 우리 파서 결함이 아니다.
 *
 * 🔴 그러므로 「채널에서 받아 자동 채우기」는 **불가능하다**. 남는 길은 둘뿐이다 —
 *   ① 셀러가 89 공통코드 `PD_ITMS_CD` 40건에서 직접 고른다(지금 동작).
 *   ② 따져가 «제안» 하고 셀러가 확인한다.
 *
 * 이 파일은 ②다. 🔴 ①을 대체하지 않는다 — 셀러의 선택이 항상 이긴다.
 *
 * ── 🔴 왜 「자동 입력」이 아니라 「제안」인가 ──────────────────────────────
 * 고시 품목은 규제 신고 항목이다. 카테고리 이름에서 추론한 값을 조용히 넣으면
 * 「따져가 정한 정책」이 규제 신고로 나간다 — 이 저장소가 반복해 금지한 것이다
 * (payload 상수에는 근거가 있어야 한다). 그래서 상태를 가른다:
 *
 *   자동 입력 가능      ✗ 채널이 값을 주지 않는다
 *   셀러 확인 필요      ✓ 이 파일의 결과는 «여기» 다
 *   Commerce 정책 확인  —
 *   등록 불가           —
 *
 * ── 🔴 아는 스키마 둘만 제안한다 ──────────────────────────────────────────
 * `notice-schema.ts` 가 실제로 아는 품목은 `"01"`(의류)·`"23"`(어린이제품)
 * 둘뿐이다. 모르는 품목을 제안하면 셀러가 고른 뒤에도 고시 표를 그릴 수 없다 —
 * 「되는 것처럼 보이는」 제안이 된다. 그래서 그 둘 밖은 제안하지 않는다.
 */

/** 제안 결과. 🔴 `code` 가 null 이면 «모른다» 이고, 그것을 숨기지 않는다. */
export interface LotteOnNoticeItemSuggestion {
  /** 제안하는 고시 품목코드. 모르면 null. */
  code: "01" | "23" | null;
  /** 셀러에게 보여줄 한 줄. 🔴 왜 그렇게 봤는지 적는다 — 근거 없는 제안을 하지 않는다. */
  reason: string;
  /** 제안의 근거가 된 카테고리 경로 토막. 없으면 빈 배열. */
  matched: string[];
}

/**
 * 🔴 어휘를 새로 만들지 않는다 — 롯데ON 카테고리 경로에 실제로 쓰이는 말만 담는다.
 *
 * 어린이제품이 «먼저» 다. 「유아동 의류」는 의류이면서 어린이제품이고, 규제가 더
 * 무거운 쪽(23 어린이제품)이 적용된다. 순서를 뒤집으면 아동복이 일반 의류 고시로
 * 신고된다.
 */
const CHILD_WORDS = ["유아", "아동", "베이비", "주니어", "키즈", "신생아", "영아", "어린이"];
const APPAREL_WORDS = [
  "의류",
  "상의",
  "하의",
  "티셔츠",
  "셔츠",
  "니트",
  "원피스",
  "바지",
  "스커트",
  "자켓",
  "재킷",
  "점퍼",
  "코트",
  "조끼",
  "트레이닝복",
  "수영복",
  "언더웨어",
  "속옷",
  "잠옷",
  "패션의류",
];

/** 🔴 「의류가 아닌데 의류 낱말이 들어간」 경로를 제안에서 뺀다 — 가방·신발·용품. */
const NOT_APPAREL_WORDS = ["가방", "지갑", "신발", "슈즈", "모자", "양말", "용품", "장비", "라켓", "공"];

function hit(parts: string[], words: string[]): string[] {
  return parts.filter((part) => words.some((word) => part.includes(word)));
}

/**
 * 카테고리 경로(대 > 중 > 소 > 세)에서 고시 품목을 «제안» 한다.
 *
 * @param path 선택된 표준카테고리의 전체 경로 이름. 없으면 이름 한 토막이라도 넣는다.
 *
 * 🔴 점수를 만들지 않는다. 카테고리 추천 랭킹(candidate-scoring.ts)과 섞이면
 *    두 판정이 생긴다 — 여기서는 「두 스키마 중 어느 쪽인가」만 가른다.
 */
export function suggestLotteOnNoticeItemCode(path: readonly string[]): LotteOnNoticeItemSuggestion {
  const parts = path.map((part) => (part ?? "").trim()).filter(Boolean);
  if (parts.length === 0) {
    return { code: null, reason: "카테고리를 먼저 선택해주세요.", matched: [] };
  }

  const notApparel = hit(parts, NOT_APPAREL_WORDS);
  const apparel = hit(parts, APPAREL_WORDS);
  /* 🔴 「테니스 가방」처럼 의류 낱말이 없고 비의류 낱말만 있으면 제안하지 않는다.
     「테니스의류」처럼 둘 다 있으면 의류가 이긴다 — 더 구체적인 낱말이다. */
  if (apparel.length === 0) {
    return notApparel.length > 0
      ? {
          code: null,
          reason: `「${notApparel.join(" · ")}」 카테고리입니다 — 의류·어린이제품 고시가 아니라 품목을 직접 골라 주세요.`,
          matched: notApparel,
        }
      : {
          code: null,
          reason: "이 카테고리의 고시 품목을 따져가 판단하지 못했습니다 — 직접 골라 주세요.",
          matched: [],
        };
  }

  const child = hit(parts, CHILD_WORDS);
  if (child.length > 0) {
    return {
      code: "23",
      reason: `카테고리에 「${child.join(" · ")}」가 있어 «어린이제품»(23) 고시로 보입니다 — 확인해 주세요.`,
      matched: [...child, ...apparel],
    };
  }
  return {
    code: "01",
    reason: `카테고리에 「${apparel.join(" · ")}」가 있어 «의류»(01) 고시로 보입니다 — 확인해 주세요.`,
    matched: apparel,
  };
}
