/**
 * ════════════════════════════════════════════════════════════════════════════
 * 롯데ON 과세유형(`tdfDvsCd`) — **닫힌 집합 넷. 의미는 문서에 있다.**
 * ════════════════════════════════════════════════════════════════════════════
 *
 * 🔴 왜 표를 «만들어도» 되는가
 *
 * 이 저장소의 원칙은 「의미를 임의로 만들지 않는다」다. 그래서 택배사·원산지·
 * 브랜드 코드는 채널 목록에서 «고르게» 하고 이름을 지어내지 않았다.
 *
 * 과세유형은 다르다 — **네 값의 의미가 문서에 적혀 있다.**
 *
 *     types.ts:168(문서 인용)  「과세유형코드 01 과세 / 02 면세 / 03 영세 / 04 해당없음」
 *
 * 우리가 번역한 것이 아니라 문서 원문의 한국어다. 그래서 고르게 할 수 있다.
 * 🔴 근거가 여기 하나뿐이므로, 값이 늘거나 이름이 달라지면 이 표가 아니라
 * 문서를 먼저 다시 본다.
 *
 * ── 🔴 왜 자유 입력을 없앴나 ──────────────────────────────────────────────
 * 화면이 도움말에 「01 과세 · 02 면세 …」를 적어 두고 셀러에게 «코드를 적게»
 * 했다. 첫 LIVE 등록(2026-09-22)이 정확히 그 모양으로 깨졌다 —
 * `note="공통코드 OPLC_CD"` 를 셀러가 답으로 옮겨 적어 `returnCode 9999`.
 *
 * ── 🔴 기본값을 «비움» 으로 바꾼 이유 ─────────────────────────────────────
 * 예전에는 세 곳이 `"01"`(과세)로 시작했다. 우리 코드가 스스로 그것을
 * 「관행 기본값」이라 불렀다(lotteon-channel-form.ts 주석). 관행은 근거가 아니다.
 *
 * 면세 상품인데 `01` 이 조용히 실려 나가면 **과세 상품으로 잘못 등록된다.**
 * 그래서 「모른다」를 «빈 값» 으로 남기고 검증기가 막는다 —
 * `UNKNOWN` 을 임의로 `01` 로 바꾸지 않는다(CPO 확정).
 */

export interface LotteOnTaxType {
  code: string;
  /** 🔴 문서 원문의 한국어. 우리 번역이 아니다. */
  name: string;
}

export const LOTTEON_TAX_TYPES: readonly LotteOnTaxType[] = [
  { code: "01", name: "과세" },
  { code: "02", name: "면세" },
  { code: "03", name: "영세" },
  { code: "04", name: "해당없음" },
];

/**
 * 셀러 화면에 쓸 이름.
 *
 * 🔴 모르는 코드면 «코드를 돌려주지 않는다» — S-19 와 같은 규칙이다.
 * 205 가 우리가 모르는 값을 줄 수도 있는데, 그때 코드를 화면에 세우면
 * 셀러가 관리할 수 없는 값을 관리하라고 보여주는 셈이 된다.
 */
export function lotteOnTaxTypeName(code: string | null | undefined): string {
  const raw = code?.trim();
  if (!raw) return "";
  return LOTTEON_TAX_TYPES.find((tax) => tax.code === raw)?.name ?? "과세 유형 확인 필요";
}

/** 우리가 아는 넷 중 하나인가. 검증기가 이것으로 막는다. */
export function isKnownLotteOnTaxType(code: string | null | undefined): boolean {
  const raw = code?.trim();
  return Boolean(raw) && LOTTEON_TAX_TYPES.some((tax) => tax.code === raw);
}
